let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('humo_lang')) || 'uz';
if (!TRANSLATIONS[currentLang]) {
  currentLang = 'uz';
}

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (TRANSLATIONS[lang]) {
    currentLang = lang;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('humo_lang', lang);
    }
    return true;
  }
  return false;
}

export function t(key, params = {}) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.uz;
  let text = dict[key] || TRANSLATIONS.uz[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}
