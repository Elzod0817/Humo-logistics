export function getCountry(code) {
  return LOCATIONS_DATA.find(c => c.code === code) || null;
}

export function isValidLocality(countryCode, localityId, isCustom = false) {
  if (isCustom) return true;
  const country = getCountry(countryCode);
  if (!country) return false;
  return country.localities.some(l => l.id === localityId);
}
